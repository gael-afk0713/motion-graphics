#!/usr/bin/env python3
"""Peixe-papagaio parte 3: sidechain ducking of the effects and the bed under the voice -> src/papagaio3/duck.ts

  python scripts/papagaio3_duck.py      (after scripts/fx_dump.mjs)

Voice activity per video frame from the 8 narration files placed exactly as in the video (RMS of each frame
above -45 dBFS). Gain per frame: -7 dB while the voice speaks (attack within one frame, ~20-33 ms), released
with a 200 ms time constant once it stops, so the effects come through in the pauses between lines.
"""
import json
import subprocess

import numpy as np

SR = 48000
D = json.load(open("out/papagaio3-fx.json", encoding="utf-8"))
FPS, S, DUR = D["FPS"], D["S"], D["DURATION"]
spf = SR // FPS
voice = np.zeros(DUR * spf + SR)
for i, nar in enumerate(D["NARRATION"]):
    pcm = subprocess.run(["ffmpeg", "-v", "error", "-i", "public/" + nar["file"], "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"], capture_output=True, check=True).stdout
    a = np.frombuffer(pcm, dtype=np.float32)
    s0 = S[i] * spf
    voice[s0 : s0 + len(a)] += a[: len(voice) - s0]
DUCK_DB = -7.0
low = 10 ** (DUCK_DB / 20)
rel = np.exp(-(1000 / FPS) / 200.0)
gains = []
g = 1.0
active = 0
for f in range(DUR):
    w = voice[f * spf : (f + 1) * spf]
    on = 20 * np.log10(np.sqrt(np.mean(w ** 2)) + 1e-12) > -45
    active += on
    g = low if on else 1 - (1 - g) * rel
    gains.append(round(g, 3))
src = ("// GENERATED by scripts/papagaio3_duck.py: sidechain ducking of the effects and the bed under the voice.\n"
       f"// Gain per video frame: {DUCK_DB:g} dB while the narration speaks (attack within a frame), 200 ms release.\n"
       "export const DUCK: readonly number[] = " + json.dumps(gains) + ";\n")
open("src/papagaio3/duck.ts", "w", encoding="utf-8", newline="\n").write(src)
print(f"duck.ts: {DUR} frames, voice active in {active} ({100 * active / DUR:.0f}%)")
