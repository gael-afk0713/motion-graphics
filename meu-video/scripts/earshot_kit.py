#!/usr/bin/env python3
"""Render a video's sound effects from the earshot bank and write the TS module the video uses.

  python3 scripts/earshot_kit.py audio/curiosario-kit.json <video>      # e.g. papagaio2

1. `earshot kit render KIT --out public/<video>/sfx/kit` renders every role's takes from the earshot
   bank (deterministic, cached, each take audited) and writes kit.lock.json with each take's measured
   onset / peak / end.
2. src/<video>/kit.ts is generated from the lock: per role its takes, their sync point (the attack,
   or a whoosh's peak) and level. `kitFx(role, frame)` returns a placement whose sync point lands on
   that frame (lead = sync point in frames), ready for the video's sfx list and for the sync check.
"""
import json
import os
import subprocess
import sys

kit_path, video = sys.argv[1], sys.argv[2]
out_dir = os.path.join("public", video, "sfx", "kit")
os.makedirs(out_dir, exist_ok=True)
subprocess.run(["earshot", "kit", "render", kit_path, "--out", out_dir], check=True)
lock = json.load(open(os.path.join(out_dir, "kit.lock.json")))

roles = {}
for name, role in lock["roles"].items():
    if not role:
        continue
    key = {"onset": "onset_s", "peak": "peak_s", "end": "end_s"}[role.get("align") or "onset"]
    roles[name] = {
        "align": role.get("align") or "onset",
        "level_db": role.get("level_db", 0.0),
        "takes": [{"file": t["file"], "sync_s": round(t[key], 4), "dur_s": round(t["dur_s"], 4),
                   "checks": t.get("checks", [])} for t in role["takes"]],
    }

ts = f"""// GENERATED by scripts/earshot_kit.py from {kit_path} - do not edit by hand.
// earshot {lock.get('earshot')}, bank {lock.get('bank')}. Files in public/{video}/sfx/kit.
export const KIT = {json.dumps(roles, indent=1)} as const;

export type KitRole = keyof typeof KIT;
export type KitFx = {{ f: number; file: string; lead: number; durS: number; volume: number; role: KitRole; align: string }};

/** an effect from the earshot kit whose sync point (attack, or a whoosh's peak) lands on frame `f`;
 *  takes rotate with `take`. file is relative to the video's SFX_DIR ("{video}/sfx"). */
export const kitFx = (role: KitRole, f: number, take = 0, fps = 30, gainDb = 0): KitFx => {{
  const r = KIT[role];
  const t = r.takes[take % r.takes.length];
  return {{
    f,
    file: `kit/${{t.file}}`,
    lead: Math.round(t.sync_s * fps),
    durS: t.dur_s,
    volume: Math.min(1, 10 ** ((r.level_db + gainDb) / 20)),
    role,
    align: r.align,
  }};
}};
"""
os.makedirs(os.path.join("src", video), exist_ok=True)
open(os.path.join("src", video, "kit.ts"), "w").write(ts)
n = sum(len(r["takes"]) for r in roles.values())
bad = [(k, t["file"], t["checks"]) for k, r in roles.items() for t in r["takes"] if t["checks"]]
print(f"{len(roles)} roles, {n} takes -> {out_dir}; src/{video}/kit.ts written; audit problems: {bad or 'none'}")
