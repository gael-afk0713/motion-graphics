import json, subprocess, re
P="/home/user/motion-graphics/meu-video/"
TEXT=[
"Você acordou | como um | peixe-papagaio. | E o seu | *cocô* | constrói *ilhas.*",
"Seus dentes | são grudados | num *bico,* | e nunca param | de crescer. | Essa é a sua | *picareta.*",
"Com ela, | você arranca | pedaços de *coral* | para comer | as algas. | Mas *coral* | é *pedra.*",
"Por isso, | você tem | um segundo par | de mandíbulas | dentro da garganta, | que mói tudo. | Esse é o seu | *moedor.*",
"O que sobra, | você solta | como *areia.* | Nas *Maldivas,* | mais de *85%* | da *areia* nova | dos recifes | vem de peixes | como você. | E as ondas | levam essa *areia* | até as *ilhas.* | Essa é a sua | *fábrica* *de* *ilhas.*",
"Mas anoitece. | E saem | *parasitas* | minúsculos | que sugam *sangue.* | Os *mosquitos* | *do* *mar.*",
"De dia, | um peixe-limpador | tira eles | de você. | Mas à noite, | ele também | *dorme.*",
"Você tem | duas opções. | *A:* | fazer um saco | de dormir | com a sua | própria baba. | *B:* | se esconder | numa fenda | do *coral.*",
"Comenta *A* | ou *B.* | A mais votada | decide se você | *sobrevive* | à noite!",
]
asr=json.load(open("words.json"))
out=[]
for i,t in enumerate(TEXT):
    f=P+f"public/papagaio/papagaio{i+1}.mp3"
    dur=float(subprocess.run(["ffprobe","-v","error","-show_entries","format=duration","-of","csv=p=0",f],capture_output=True,text=True).stdout)
    log=subprocess.run(["ffmpeg","-hide_banner","-i",f,"-af","silencedetect=noise=-30dB:d=0.05","-f","null","-"],capture_output=True,text=True).stderr
    ss=[float(x) for x in re.findall(r"silence_start: ([0-9.]+)",log)]
    se=[float(x) for x in re.findall(r"silence_end: ([0-9.]+)",log)]
    sil=list(zip(ss,se))
    words=[w for w in t.replace("|"," ").split()]
    a=asr[str(i+1)]; k=0; times=[]
    for w in words:
        times.append(a[k][0]); k+=2 if "-" in w else 1
    assert k==len(a),(i,k,len(a))
    sn=[]
    for j,x in enumerate(times):
        y=x+0.02
        for s,e in sil:
            if s-0.02<=x<=e or 0<e-x<=0.12: y=e
        if j==0: y=sil[0][1] if sil and sil[0][0]<=0.01 else 0
        if sn and y<=sn[-1]: y=sn[-1]+0.08
        sn.append(round(y,3))
    print(i+1, round(dur,3), list(zip([w.strip('*') for w in words],sn)))
    out.append({"file":f"papagaio/papagaio{i+1}.mp3","dur":round(dur,6),"text":t,"t":sn})
src="// generated by scripts/papagaio_words.py: narration text (exact), caption chunks (' | '),\n// yellow keywords (*word*) and the start of each spoken word in seconds (ASR alignment\n// snapped to the pauses found by ffmpeg silencedetect). dur = ffprobe duration.\nexport const NARRATION = "+json.dumps(out,ensure_ascii=False,indent=1)+" as const;\n"
import os; os.makedirs(P+"src/papagaio",exist_ok=True)
open(P+"src/papagaio/words.ts","w").write(src)
